import yfinance as yf
import pandas as pd
import numpy as np
from sklearn.preprocessing import MinMaxScaler


class marketdatacollector:
    def __init__(self, tickers: list, start_date: str, end_date: str):
        self.tickers = tickers
        self.start_date = start_date
        self.end_date = end_date
        self.scalers = {}

    def fetch_data(self) -> pd.DataFrame:
        print(f"Fetching market data for {len(self.tickers)} tickers...")
        raw_data = yf.download(self.tickers, start=self.start_date, end=self.end_date, group_by='ticker')

        processed_dfs = []
        for ticker in self.tickers:
            # handle single vs multiple ticker formatting from yfinance
            if len(self.tickers) == 1:
                df = raw_data.copy()
            else:
                df = raw_data[ticker].copy()

            df['ticker'] = ticker

            # 1. engineer past observed features (technical indicators)
            df['returns'] = df['Close'].pct_change()
            df['volatility_7d'] = df['returns'].rolling(window=7).std()

            # simple rsi calculation
            delta = df['Close'].diff()
            gain = (delta.where(delta > 0, 0)).rolling(window=14).mean()
            loss = (-delta.where(delta < 0, 0)).rolling(window=14).mean()
            rs = gain / loss
            df['rsi_14'] = 100 - (100 / (1 + rs))

            # 2. engineer known future features (calendar/time covariates)
            # these must be known independent of the market state
            df['day_of_week'] = df.index.dayofweek
            df['month'] = df.index.month
            df['day_of_month'] = df.index.day

            # drop nan values generated by rolling windows
            df.dropna(inplace=True)
            processed_dfs.append(df)

        return pd.concat(processed_dfs)

    def scale_features(self, df: pd.DataFrame, features_to_scale: list) -> pd.DataFrame:
        scaled_df = df.copy()

        # we scale per ticker to prevent high-price stocks from dominating the loss gradients
        for ticker in df['ticker'].unique():
            mask = scaled_df['ticker'] == ticker
            scaler = MinMaxScaler()

            scaled_df.loc[mask, features_to_scale] = scaler.fit_transform(
                scaled_df.loc[mask, features_to_scale]
            )
            self.scalers[ticker] = scaler

        return scaled_df


# example usage block to verify the pipeline
if __name__ == "__main__":
    pipeline = marketdatacollector(
        tickers=["AAPL", "MSFT", "NVDA"],
        start_date="2020-01-01",
        end_date="2026-05-01"
    )

    master_df = pipeline.fetch_data()

    # define exactly what goes into the temporal fusion transformer
    continuous_features = ['Close', 'Volume', 'returns', 'volatility_7d', 'rsi_14']
    final_df = pipeline.scale_features(master_df, continuous_features)

    print("\nData Engineering Complete.")
    print(f"Total shape ready for dataset generation: {final_df.shape}")
    print(final_df.head())